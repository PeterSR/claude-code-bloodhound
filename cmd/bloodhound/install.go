package main

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/spf13/cobra"

	"github.com/PeterSR/claude-code-bloodhound/internal/config"
)

var (
	installEnable bool
	installForce  bool
)

var installCmd = &cobra.Command{
	Use:   "install",
	Short: "Install the OS service appropriate to this platform",
	Long: `Writes the OS-native unit files so the daemon runs in the background:

  Linux:   ~/.config/systemd/user/bloodhound.service
  macOS / Windows: not yet implemented

The systemd path is generated against the absolute path of the running
binary; move the binary and re-run install. By default the unit file is
written but the service is not enabled — pass --enable to also run
'systemctl --user enable --now bloodhound.service'.`,
}

var uninstallCmd = &cobra.Command{
	Use:   "uninstall",
	Short: "Remove the OS service installed by `bloodhound install`",
}

const linuxUnitTemplate = `# Generated by ` + "`bloodhound install`" + `. Re-run install to refresh.
[Unit]
Description=Claude Code Bloodhound — usage collector
After=default.target

[Service]
Type=simple
# Pin CWD to bloodhound's own state dir so the /usage scraper's claude
# invocation triggers its "is this folder trusted?" check against a
# small, daemon-owned directory (one-time prompt, auto-answered by the
# driver) rather than $HOME (broad, surprising). Re-run install --force
# if you move the state dir.
WorkingDirectory=%s
# Inherit the user's PATH captured at install time. systemd-user's
# default PATH is just /usr/local/bin:/usr/bin, which won't find
# claude when it lives under ~/.local/bin, ~/.nvm/..., etc.
Environment=PATH=%s
ExecStart=%s daemon
Restart=on-failure
RestartSec=10s

[Install]
WantedBy=default.target
`

func installLinuxImpl(out interface{ Write(p []byte) (int, error) }) error {
	// Path of this very binary.
	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate executable: %w", err)
	}
	exe, err = filepath.EvalSymlinks(exe)
	if err != nil {
		return fmt.Errorf("resolve executable: %w", err)
	}

	// Resolve and create the state dir up front; systemd refuses to
	// start a service whose WorkingDirectory doesn't exist.
	stateDir, err := config.StateDir()
	if err != nil {
		return fmt.Errorf("resolve state dir: %w", err)
	}
	if err := config.EnsureDir(stateDir); err != nil {
		return err
	}

	unitDir, err := linuxUnitDir()
	if err != nil {
		return err
	}
	if err := config.EnsureDir(unitDir); err != nil {
		return err
	}
	unitPath := filepath.Join(unitDir, "bloodhound.service")

	if _, err := os.Stat(unitPath); err == nil && !installForce {
		fmt.Fprintf(out, "service already exists: %s (pass --force to overwrite)\n", unitPath)
	} else {
		userPATH := os.Getenv("PATH")
		if userPATH == "" {
			userPATH = "/usr/local/bin:/usr/bin"
		}
		body := fmt.Sprintf(linuxUnitTemplate, stateDir, userPATH, exe)
		if err := os.WriteFile(unitPath, []byte(body), 0o644); err != nil {
			return fmt.Errorf("write unit: %w", err)
		}
		fmt.Fprintf(out, "wrote %s\n", unitPath)
	}

	if installEnable {
		if err := runSystemctlUser(out, "daemon-reload"); err != nil {
			return err
		}
		if err := runSystemctlUser(out, "enable", "--now", "bloodhound.service"); err != nil {
			return err
		}
		fmt.Fprintln(out, "service enabled and started")
	} else {
		fmt.Fprintln(out, "to start now:  systemctl --user daemon-reload && systemctl --user enable --now bloodhound.service")
	}
	return nil
}

func uninstallLinux(out interface{ Write(p []byte) (int, error) }) error {
	unitDir, err := linuxUnitDir()
	if err != nil {
		return err
	}
	unitPath := filepath.Join(unitDir, "bloodhound.service")
	// Best-effort stop + disable; ignore errors so a partial install can
	// still be cleaned up.
	_ = runSystemctlUser(out, "disable", "--now", "bloodhound.service")
	if err := os.Remove(unitPath); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			fmt.Fprintf(out, "no unit file at %s\n", unitPath)
		} else {
			return err
		}
	} else {
		fmt.Fprintf(out, "removed %s\n", unitPath)
	}
	_ = runSystemctlUser(out, "daemon-reload")
	return nil
}

func linuxUnitDir() (string, error) {
	if dir := os.Getenv("XDG_CONFIG_HOME"); dir != "" {
		return filepath.Join(dir, "systemd", "user"), nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".config", "systemd", "user"), nil
}

func runSystemctlUser(out interface{ Write(p []byte) (int, error) }, args ...string) error {
	cmd := exec.Command("systemctl", append([]string{"--user"}, args...)...)
	combined, err := cmd.CombinedOutput()
	if len(combined) > 0 {
		_, _ = out.Write(combined)
	}
	if err != nil {
		// Suppress noise for common "service not found" on uninstall.
		if strings.Contains(string(combined), "Unit bloodhound.service does not exist") {
			return nil
		}
		return fmt.Errorf("systemctl --user %s: %w", strings.Join(args, " "), err)
	}
	return nil
}

func init() {
	installCmd.RunE = func(cmd *cobra.Command, _ []string) error {
		switch runtime.GOOS {
		case "linux":
			return installLinuxImpl(cmd.OutOrStdout())
		default:
			return fmt.Errorf("install: %s installer not yet implemented", runtime.GOOS)
		}
	}
	uninstallCmd.RunE = func(cmd *cobra.Command, _ []string) error {
		switch runtime.GOOS {
		case "linux":
			return uninstallLinux(cmd.OutOrStdout())
		default:
			return fmt.Errorf("uninstall: %s not yet implemented", runtime.GOOS)
		}
	}
	installCmd.Flags().BoolVar(&installEnable, "enable", false, "also run systemctl --user enable --now after writing the unit")
	installCmd.Flags().BoolVar(&installForce, "force", false, "overwrite an existing unit file")
	rootCmd.AddCommand(installCmd)
	rootCmd.AddCommand(uninstallCmd)
}
